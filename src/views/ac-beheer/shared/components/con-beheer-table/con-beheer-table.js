import { forwardRef, useEffect, useMemo, useState, useCallback } from 'react';
import { useNavigate } from 'react-router';
import ConTable from '@views/ac-beheer/shared/components/con-table';
import { VISUALS } from '@src/constants';
import { useLaterEffect } from '@src/hooks';
import ConActionMenu from '@views/ac-beheer/shared/components/con-action-menu';
import { canReadField } from '@utils/field-authorization';
import BeheerPageConfigFactory from '@views/ac-beheer/core/factories/con-beheer-page-config-factory';
import { withStore } from '@stores';
import { observer } from 'mobx-react-lite';
import _ from 'lodash';

// Local navigation builder based on config.routeType
const buildNavigateView = (navigate, config) => (rowOrId) => {
  const id =
    typeof rowOrId === 'object' && rowOrId !== null
      ? rowOrId?.['@self']?.id ?? rowOrId?.id
      : rowOrId;

  return navigate(`/beheer/${config.routeType}/${id}`);
};

/**
 * @typedef {Object} typeProps
 * @param {
 * 'voorzieningen'
 * | 'applicaties'
 * | 'voorzieningaanboden'
 * | 'diensten'
 * | 'voorzieninggebruiken'
 * | 'gebruiken'
 * | 'voorzieningversies'
 * | 'versies'
 * | 'contracten'
 * | 'overeenkomsten'
 * | 'organisaties'
 * | 'kwetsbaarheden'
 * | 'gebruikers'
 * | 'contactpersoon'
 * | 'contactpersonen'
 * } type
 */

/**
 * @param {typeProps} props.type - The type of the table
 * @param {Object} props.metadata - If not type is given, use metadata to get the config. (Errors if both type and metadata are not given)
 * @param {function} props.getSelectedRows - function that gets called when a row is selected. Returns the selected rows.
 * @param {function} props.getSingleSelectedRow - function that gets called when a single row is selected. Returns the selected row.
 * @param {function} props.getModalValue - function that gets called when an action button is clicked and sets the modal to a value. Returns any string, e.g. 'edit' or 'delete'.
 * @param {Object} props.headerOverrides - object that contains custom content for the table headers.
 * @param {function} props.getHeaders - gets the headers generated by the component
 * @param {function} props.headers - sets the headers to custom headers, takes precedence over the headers generated by the component
 * @param {function} props.getDefaultHeaders - gets the default headers from the specified type
 * @param {(searchValues: { [headerId: string]: string }) => void} props.onHeaderSearch - Callback function called when any header search value changes. Receives an object with all current search values as parameters.
 * @returns
 */
const BeheerTable = forwardRef(({ store, ...props }, ref) => {
  const {
    type,
    metadata,
    data: providedData = [],
    dataProperties: providedDataProperties = [],
    getSelectedRows,
    getSingleSelectedRow,
    getModalValue,
    headerOverrides,
    getLoading = () => false,
    getHeaders = () => [],
    headers: providedHeaders = [],
    getDefaultHeaders = () => [],
    actionButtons: overrideActionButtons = null,
    getConfig = () => {},
    tableProps = {},
    pagination = {},
    setPagination = () => {},
    onHeaderSearch,
    user = null, // User object for authorization checks
  } = props;

  if (!type && !metadata) {
    throw new Error('Either type or metadata (@self) must be provided');
  }

  const navigate = useNavigate();
  const objectStore = store?.object;

  const shouldFetchData = !providedData?.length;
  const shouldFetchDataProperties = !providedDataProperties?.length;

  const [data, setData] = useState([]);
  const [dataProperties, setDataProperties] = useState({});
  const [loading, setLoading] = useState(false);

  const [tableHeaders, setTableHeaders] = useState([]);

  const config = useMemo(() => {
    // Prefer factory when type is provided; otherwise derive minimal config from metadata
    let cfg = null;
    if (type) {
      try {
        cfg = BeheerPageConfigFactory.createConfig(type);
      } catch (e) {
        cfg = null;
      }
    }
    if (!cfg && metadata) {
      cfg = {
        registerSlug: metadata.register?.id ?? metadata.register ?? 'voorzieningen',
        schemaSlug: metadata.schema?.id ?? metadata.schema,
        routeType: metadata.schema?.slug || metadata.schema || type || 'objects',
        extend: ['all'],
        defaultHeaders: [],
        customHeaders: {},
        removeHeaders: [],
      };
    }
    if (!cfg) {
      // Fallback to type as-is
      cfg = BeheerPageConfigFactory.createConfig(type);
    }
    // Compose navigateView locally
    const navigateView = buildNavigateView(navigate, cfg);
    const finalCfg = { ...cfg, navigateView };
    getConfig?.(finalCfg);
    return finalCfg;
  }, [type, navigate, metadata]);

  const fetchObjectData = async (searchParams = {}) => {
    if (!objectStore) return;

    const params = {
      _limit: pagination?.limit || 9999,
      _page: pagination?.page || 1,
      ...searchParams,
    };

    try {
      await objectStore.fetchCollection(
        config.registerSlug,
        config.schemaSlug,
        { ...params, _published: 'false' }
      );

      const typeKey = objectStore.getTypeFromParams(
        config.registerSlug,
        config.schemaSlug
      );
      const col = objectStore.getCollection(typeKey);
      const pag = objectStore.getPagination(typeKey);

      setData(col.results || []);
      setPagination((prev) => ({
        ...prev,
        total: pag.total,
        pages: pag.pages,
        offset: pag.offset,
      }));
      return { results: col.results || [], ...pag };
    } catch (e) {
      return { error: e?.message };
    }
  };

  const fetchSchemaData = async () => {
    if (!objectStore) return;
    try {
      await objectStore.fetchSchema(config.schemaSlug);
      const schemaType = objectStore.getSchemaType(config.schemaSlug);
      const props = objectStore.getSchemaProperties(schemaType);
      setDataProperties(props);
      return { properties: props };
    } catch (e) {
      return { error: e?.message };
    }
  };

  useEffect(async () => {
    // Return early if no fetching needed
    if (!shouldFetchData && !shouldFetchDataProperties) {
      return;
    }

    try {
      setLoading(true);
      getLoading?.(true);

      if (shouldFetchData) {
        await fetchObjectData();
      }
      if (shouldFetchDataProperties) {
        await fetchSchemaData();
      }
    } catch (err) {
      console.error('Error fetching data:', err);
    } finally {
      setLoading(false);
      getLoading?.(false);
    }
  }, []);

  useEffect(() => {
    if (!shouldFetchData) {
      setData(providedData);
    }
  }, [providedData]);

  useEffect(() => {
    if (!shouldFetchDataProperties) {
      setDataProperties(providedDataProperties);
    }
  }, [providedDataProperties]);

  useLaterEffect(async () => {
    if (!shouldFetchData) return;

    try {
      setLoading(true);
      getLoading?.(true);

      await fetchObjectData();
    } catch (err) {
      console.error('Error fetching data:', err);
    } finally {
      setLoading(false);
      getLoading?.(false);
    }
  }, [pagination.page, pagination.limit]);

  // Generate headers from dataProperties schema
  const generatedHeaders = useMemo(() => {
    if (!dataProperties) return [];

    const schemaHeaders = Object.entries(dataProperties)
      .filter(
        ([, value]) => value.visible !== false && value.hideOnCollection !== true
      )
      .filter(([, value]) => canReadField(user, value))
      .flatMap(([key, value]) => {
        // leverancier from diensten is a special case as its referenced twice
        if (headerOverrides && type === 'diensten' && key === 'leverancier') {
          return [
            { ...(headerOverrides?.['leverancier_naam'] || {}), sourceKey: key },
            { ...(headerOverrides?.['leverancier_email'] || {}), sourceKey: key },
          ];
        }

        // Check if we have a custom override for this header (component-level)
        if (headerOverrides?.[key]) {
          return { ...headerOverrides[key], sourceKey: key };
        }

        // Try factory config custom headers if override doesn't exist
        if (config.customHeaders?.[key]) {
          return { ...config.customHeaders[key], sourceKey: key };
        }

        // Generate standard header from schema
        // Use schema property title if available, otherwise capitalize the key
        const label =
          value.title && value.title.trim() ? value.title : _.upperFirst(key);

        return {
          id: key,
          label: label,
          key: key,
          sourceKey: key,
        };
      })
      // Filter out headers that are in the removeHeaders config
      .filter((header) => !config.removeHeaders?.includes(header.id));

    return schemaHeaders;
  }, [
    dataProperties,
    headerOverrides,
    config.removeHeaders,
    user,
    type,
    config.defaultHeaders,
  ]);

  const { defaultHeaderIds, shouldShowAllHeaders } = useMemo(() => {
    if (!dataProperties) return { defaultHeaderIds: [], shouldShowAllHeaders: true };

    const entries = Object.entries(dataProperties);
    const anyTable = entries.some(([, value]) => !!value?.table);
    const defaultTrueKeys = new Set(
      entries.filter(([, value]) => value?.table?.default === true).map(([k]) => k)
    );

    const showAll = !anyTable || defaultTrueKeys.size === 0;

    if (showAll) {
      return { defaultHeaderIds: [], shouldShowAllHeaders: true };
    }

    const ids = generatedHeaders
      .filter((h) => defaultTrueKeys.has(h.sourceKey || h.id))
      .map((h) => h.id);

    return { defaultHeaderIds: ids, shouldShowAllHeaders: false };
  }, [dataProperties, generatedHeaders]);

  useEffect(() => {
    getHeaders?.(generatedHeaders);
    getDefaultHeaders?.(shouldShowAllHeaders ? [] : defaultHeaderIds);

    // default headers if `headers` is not being used
    if (generatedHeaders.length > 0) {
      setTableHeaders(
        generatedHeaders.filter(
          (header) => shouldShowAllHeaders || defaultHeaderIds.includes(header.id)
        )
      );
    }
  }, [
    generatedHeaders,
    getHeaders,
    getDefaultHeaders,
    defaultHeaderIds,
    shouldShowAllHeaders,
  ]);

  // if no overrideActionButtons are provided, use the default action buttons
  const overrideActionsIsValid =
    !!overrideActionButtons && typeof overrideActionButtons === 'function';

  const actionButtons = overrideActionsIsValid
    ? overrideActionButtons(config)
    : {
        id: 'actions',
        label: 'Acties',
        key: '',
        customContent: (row) => (
          <ConActionMenu>
            <ConActionMenu.Trigger
              icon={<VISUALS.ELLIPSIS />}
              buttonType='secondary'
            >
              Acties
            </ConActionMenu.Trigger>

            <ConActionMenu.Menu position='right'>
              <ConActionMenu.Button
                icon={<VISUALS.EYE />}
                onClick={() => {
                  config.navigateView(row);
                }}
              >
                Bekijken
              </ConActionMenu.Button>

              <ConActionMenu.Button
                icon={<VISUALS.PENCIL />}
                onClick={() => {
                  getSingleSelectedRow?.(row);
                  getModalValue?.('edit');
                }}
              >
                Bewerken
              </ConActionMenu.Button>

              <ConActionMenu.Button
                icon={<VISUALS.TRASHCAN />}
                onClick={() => {
                  getSingleSelectedRow?.(row);
                  getModalValue?.('delete');
                }}
              >
                Verwijderen
              </ConActionMenu.Button>
            </ConActionMenu.Menu>
          </ConActionMenu>
        ),
      };

  // ✅ Add handler for header search
  const handleHeaderSearch = useCallback(
    (searchValues) => {
      // Call the parent's onHeaderSearch callback if provided
      if (typeof onHeaderSearch === 'function') {
        onHeaderSearch(searchValues);
      } else {
        // If no parent callback, refetch data with search parameters
        fetchObjectData(searchValues);
      }
    },
    [onHeaderSearch]
  );

  return (
    <ConTable
      data={data}
      dataProperties={dataProperties}
      // `providedHeaders` takes precedence over the tableHeaders generated by the component
      tableHeaders={[
        ...(providedHeaders?.length ? providedHeaders : tableHeaders),
        ...(actionButtons ? [actionButtons] : []),
      ]}
      getSelectedRows={getSelectedRows}
      renderSelectRowButtons
      ref={ref}
      truncateLines={3}
      showSortButtons
      loading={loading}
      onHeaderSearch={handleHeaderSearch}
      {...tableProps}
    />
  );
});
BeheerTable.displayName = 'BeheerTable';

export default withStore(observer(BeheerTable));
